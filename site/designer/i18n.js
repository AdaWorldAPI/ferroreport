const DICT = { en, es };

function detect() {
  let saved = null;
  try { saved = localStorage.getItem(LANG_KEY); } catch { /* blocked */ }
  if (saved && DICT[saved]) return saved;
  const nav = (typeof navigator !== "undefined" && (navigator.language || (navigator.languages || [])[0])) || "en";
  return /^es\b/i.test(nav) ? "es" : "en";
}

let current = typeof document !== "undefined" ? detect() : "en";

/** The language the page is in: "en" or "es". */
export const lang = () => current;

/** The text of `key` in the page's language, with {name} filled in from `vars`. */
export function t(key, vars = {}, fallback) {
  const s = DICT[current][key] ?? en[key] ?? fallback ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Changes the language, remembers it, and translates the page's own text. */
export function setLang(l) {
  if (!DICT[l]) return;
  current = l;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* blocked */ }
  applyStatic();
}

/** Puts the words of index.html in the page's language. */
export function applyStatic() {
  document.documentElement.lang = current;
  document.title = t("doc.title");
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
}

export const DICTIONARY = DICT;
